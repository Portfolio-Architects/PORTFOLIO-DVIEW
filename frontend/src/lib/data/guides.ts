/**
 * Normalizes apartment complex display names and tx-summary keys into a canonical lookup token
 * so spaced UI aliases (e.g. '동탄역 시범 리슈빌', '예당마을 우미린 제일풍경채') resolve deterministically
 * to their exact guide entries without false substring collisions.
 */
export function normalizeGuideAptName(rawName: string | undefined): string {
  if (!rawName) return '';
  let norm = rawName
    .toLowerCase()
    .replace(/\s+/g, '')
    .replace(/[()]/g, '')
    .replace(/아파트$/g, '')
    .replace(/^e편한세상/, '이편한세상');

  if (norm === '동탄역시범더샵센트럴시티') norm = '더샵센트럴시티';
  else if (norm === '동탄역시범반도유보라아이비파크4.0') norm = '시범반도유보라아이비파크4.0';
  else if (norm === '동탄역센트럴자이') norm = '동탄역센트럴자이a-10';
  else if (norm === '능동역이지더원') norm = '능동마을이지더원';
  else if (norm.startsWith('예당마을') && norm.length > 4) norm = norm.slice(4);
  else if (norm.startsWith('동탄푸른마을')) norm = norm.slice(2);

  return norm;
}

export interface RelatedGuidesResult {
  relatedGuides: GuideArticle[];
  directGuides: GuideArticle[];
  hasDirectMatch: boolean;
  zone?: ZoneInfo;
}

/**
 * Resolves comparison guides directly featuring an apartment (1:1 headToHeadComparisons prioritized first,
 * followed by featuredApartments), padding up to `minPadCount` with zone-level guides only when `dong` is
 * a verified Dongtan legal/administrative dong (preventing ghost slugs from leaking 'gbcx' fallback links).
 */
export function getRelatedGuidesForApartment(params: {
  aptName?: string;
  resolvedTxKey?: string;
  dong?: string;
  minPadCount?: number;
  maxTotal?: number;
}): RelatedGuidesResult {
  const { aptName, resolvedTxKey, dong, minPadCount = 3, maxTotal } = params;
  const trimmedDong = (dong || '').trim();
  const hasValidDong = KNOWN_DONGTAN_DONGS.has(trimmedDong);
  const normalizedDong = trimmedDong === '오산동' ? '여울동' : trimmedDong;
  const zoneId = hasValidDong ? dongToZoneId(normalizedDong) : undefined;
  const zone = zoneId ? getZoneById(zoneId) : undefined;

  const candidateNorms = new Set(
    [normalizeGuideAptName(aptName), normalizeGuideAptName(resolvedTxKey)].filter(
      (n) => n.length >= 3
    )
  );

  const matchesGuideAptKey = (guideAptKey: string): boolean => {
    const keyNorm = normalizeGuideAptName(guideAptKey);
    if (!keyNorm || !candidateNorms.has(keyNorm)) return false;
    if (keyNorm === '롯데캐슬' && hasValidDong && normalizedDong !== '석우동') {
      return false;
    }
    return true;
  };

  const isHeadToHeadMatch = (article: GuideArticle) =>
    (article.headToHeadComparisons || []).some(
      (m) => matchesGuideAptKey(m.leftApt) || matchesGuideAptKey(m.rightApt)
    );
  const isFeaturedAptMatch = (article: GuideArticle) =>
    (article.featuredApartments || []).some((k) => matchesGuideAptKey(k));

  const directGuides = GUIDE_ARTICLES.filter(
    (a) => isHeadToHeadMatch(a) || isFeaturedAptMatch(a)
  ).sort((a, b) => {
    const scoreDiff = Number(isHeadToHeadMatch(b)) - Number(isHeadToHeadMatch(a));
    if (scoreDiff !== 0) return scoreDiff;
    if (zoneId) {
      const zoneMatchDiff =
        Number((b.featuredZones || []).includes(zoneId)) -
        Number((a.featuredZones || []).includes(zoneId));
      if (zoneMatchDiff !== 0) return zoneMatchDiff;
    }
    const specificityDiff =
      (a.featuredZones?.length || 99) - (b.featuredZones?.length || 99);
    if (specificityDiff !== 0) return specificityDiff;
    const updatedDiff = (b.updatedDate || b.date || '').localeCompare(
      a.updatedDate || a.date || ''
    );
    if (updatedDiff !== 0) return updatedDiff;
    return (b.date || '').localeCompare(a.date || '');
  });

  const zoneGuides = zoneId
    ? GUIDE_ARTICLES.filter(
        (a) =>
          (a.featuredZones || []).includes(zoneId) &&
          !directGuides.some((d) => d.slug === a.slug)
      ).sort((a, b) => {
        const specificityDiff =
          (a.featuredZones?.length || 99) - (b.featuredZones?.length || 99);
        if (specificityDiff !== 0) return specificityDiff;
        const updatedDiff = (b.updatedDate || b.date || '').localeCompare(
          a.updatedDate || a.date || ''
        );
        if (updatedDiff !== 0) return updatedDiff;
        return (b.date || '').localeCompare(a.date || '');
      })
    : [];

  const combined = [
    ...directGuides,
    ...zoneGuides.slice(0, Math.max(0, minPadCount - directGuides.length)),
  ];

  const relatedGuides =
    typeof maxTotal === 'number' && maxTotal > 0 ? combined.slice(0, maxTotal) : combined;

  return {
    relatedGuides,
    directGuides,
    hasDirectMatch: directGuides.length > 0,
    zone,
  };
}

export function buildGuideArticleJsonLd(
  article: GuideArticle,
  baseUrl = 'https://dongtanview.com'
) {
  const currentUrl = `${baseUrl}/guide/${article.slug}`;
  const graph: Array<Record<string, unknown>> = [
    {
      '@type': 'Article',
      '@id': `${currentUrl}#article`,
      headline: article.title,
      alternativeHeadline: article.seoTitle || article.subtitle,
      description: article.seoDescription || article.description,
      datePublished: article.date,
      dateModified: article.updatedDate || article.date,
      author: {
        '@type': 'Organization',
        name: article.author,
        url: baseUrl,
      },
      publisher: {
        '@type': 'Organization',
        name: 'D-VIEW 부동산 데이터 랩스',
        url: baseUrl,
      },
      mainEntityOfPage: {
        '@type': 'WebPage',
        '@id': currentUrl,
      },
      keywords: article.tags.join(','),
    },
    {
      '@type': 'BreadcrumbList',
      '@id': `${currentUrl}#breadcrumb`,
      itemListElement: [
        {
          '@type': 'ListItem',
          position: 1,
          name: '홈',
          item: baseUrl,
        },
        {
          '@type': 'ListItem',
          position: 2,
          name: '동탄 부동산 가이드',
          item: `${baseUrl}/guide`,
        },
        {
          '@type': 'ListItem',
          position: 3,
          name: article.title,
          item: currentUrl,
        },
      ],
    },
  ];

  if (article.faqs && article.faqs.length > 0) {
    graph.push({
      '@type': 'FAQPage',
      '@id': `${currentUrl}#faq`,
      mainEntity: article.faqs.map((faq) => ({
        '@type': 'Question',
        name: faq.question,
        acceptedAnswer: {
          '@type': 'Answer',
          text: faq.answer,
        },
      })),
    });
  }

  return {
    '@context': 'https://schema.org',
    '@graph': graph,
  };
}


